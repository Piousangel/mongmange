/** 납작 타원 면 — 아래 꼭짓점에서 시작(칠이 아래에서 짙다) */
function flat(cx: number, cy: number, rx: number, ry: number): string {
  const k = 0.5523;
  const p = (x: number, y: number) => `${f1(x)} ${f1(y)}`;
  return (
    `M${p(cx, cy + ry)} C${p(cx + rx * k, cy + ry)} ${p(cx + rx, cy + ry * k)} ${p(cx + rx, cy)} C${p(cx + rx, cy - ry * k)} ${p(cx + rx * k, cy - ry)} ${p(cx, cy - ry)} ` +
    `C${p(cx - rx * k, cy - ry)} ${p(cx - rx, cy - ry * k)} ${p(cx - rx, cy)} C${p(cx - rx, cy + ry * k)} ${p(cx - rx * k, cy + ry)} ${p(cx, cy + ry)}`
  );
}

